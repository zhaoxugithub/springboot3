package com.atguigu.boot.lifecycle;

/**
 * Bean 生命周期流程图（文本版）
 *
 * ┌─────────────────────────────────────────────────────────────────┐
 * │                    Spring Bean 生命周期                          │
 * └─────────────────────────────────────────────────────────────────┘
 *
 * 【创建阶段】
 *
 *   ┌───────────────────────────────────────────────────────────┐
 *   │  1. 实例化（Instantiation）                                │
 *   │     - Spring 容器通过反射调用构造器创建 Bean 实例            │
 *   │     - 此时对象已存在，但属性未赋值                           │
 *   └───────────────────────────────────────────────────────────┘
 *                              ↓
 *   ┌───────────────────────────────────────────────────────────┐
 *   │  2. 属性赋值（Populate Properties）                        │
 *   │     - 通过 setter 方法或字段注入依赖                        │
 *   │     - @Autowired、@Resource、@Value 等注解在此阶段生效       │
 *   └───────────────────────────────────────────────────────────┘
 *                              ↓
 * 【初始化阶段】
 *
 *   ┌───────────────────────────────────────────────────────────┐
 *   │  3. Aware 接口回调                                          │
 *   │     - BeanNameAware.setBeanName()                         │
 *   │     - BeanFactoryAware.setBeanFactory()                   │
 *   │     - ApplicationContextAware.setApplicationContext()     │
 *   └───────────────────────────────────────────────────────────┘
 *                              ↓
 *   ┌───────────────────────────────────────────────────────────┐
 *   │  4. BeanPostProcessor 前置处理                             │
 *   │     - postProcessBeforeInitialization()                   │
 *   │     - 在初始化方法之前调用                                   │
 *   │     - 可用于属性校验、日志记录等                             │
 *   └───────────────────────────────────────────────────────────┘
 *                              ↓
 *   ┌───────────────────────────────────────────────────────────┐
 *   │  5. 初始化方法（按顺序执行）                                 │
 *   │     ① @PostConstruct 注解的方法                            │
 *   │     ② InitializingBean.afterPropertiesSet()               │
 *   │     ③ 自定义 init-method                                   │
 *   └───────────────────────────────────────────────────────────┘
 *                              ↓
 *   ┌───────────────────────────────────────────────────────────┐
 *   │  6. BeanPostProcessor 后置处理 ⭐ 重要！                    │
 *   │     - postProcessAfterInitialization()                    │
 *   │     - 在初始化方法之后调用                                   │
 *   │     - 可以返回代理对象（AOP 实现原理）                       │
 *   └───────────────────────────────────────────────────────────┘
 *                              ↓
 * 【使用阶段】
 *
 *   ┌───────────────────────────────────────────────────────────┐
 *   │  7. Bean 就绪，可以使用                                     │
 *   │     - 此时 Bean 已完全初始化，可以处理业务请求               │
 *   │     - Bean 被应用程序正常使用                               │
 *   └───────────────────────────────────────────────────────────┘
 *                              ↓
 * 【销毁阶段】（容器关闭时触发）
 *
 *   ┌───────────────────────────────────────────────────────────┐
 *   │  8. 销毁方法（按顺序执行）                                   │
 *   │     ① @PreDestroy 注解的方法                               │
 *   │     ② DisposableBean.destroy()                            │
 *   │     ③ 自定义 destroy-method                                │
 *   └───────────────────────────────────────────────────────────┘
 *                              ↓
 *   ┌───────────────────────────────────────────────────────────┐
 *   │  9. Bean 被销毁                                             │
 *   │     - 对象被垃圾回收                                         │
 *   │     - 生命周期结束                                           │
 *   └───────────────────────────────────────────────────────────┘
 *
 *
 * ═══════════════════════════════════════════════════════════════
 *
 * 【核心扩展点】
 *
 * 1. BeanPostProcessor（Bean 后置处理器）
 *    - Spring 框架最重要的扩展点之一
 *    - 作用于容器中的所有 Bean
 *    - AOP、事务、缓存等功能都基于此实现
 *
 * 2. Aware 接口家族
 *    - 让 Bean 感知 Spring 容器环境
 *    - 获取容器相关的信息和资源
 *
 * 3. 初始化和销毁方法
 *    - 提供三种方式：注解、接口、配置
 *    - 推荐使用注解或配置方式（解耦）
 *
 * ═══════════════════════════════════════════════════════════════
 *
 * 【最佳实践】
 *
 * ✅ 推荐做法：
 * - 使用 @PostConstruct 和 @PreDestroy（简洁清晰）
 * - 或使用 @Bean(initMethod, destroyMethod)（完全解耦）
 * - 构造器注入依赖（不可变，便于测试）
 *
 * ❌ 不推荐做法：
 * - 实现 InitializingBean 和 DisposableBean（与 Spring 耦合）
 * - 在构造器中执行复杂逻辑（此时依赖未注入）
 * - 在销毁方法中抛出异常（可能导致其他 Bean 无法正常销毁）
 *
 * ═══════════════════════════════════════════════════════════════
 *
 * 【常见应用场景】
 *
 * 初始化阶段：
 * - 初始化线程池、连接池
 * - 建立网络连接
 * - 加载配置文件、缓存数据
 * - 启动定时任务
 * - 预热缓存
 *
 * 销毁阶段：
 * - 关闭线程池、连接池
 * - 释放系统资源
 * - 保存状态数据
 * - 停止定时任务
 * - 清理临时文件
 *
 * ═══════════════════════════════════════════════════════════════
 *
 *
 *  -十步骤版本Bean的生命周期
 * 1.实例化
 * 2.依赖注入
 * 3.BeanNameAware BeanFactoryAare方法执行啦!
 * 4.初始化前 BeanPostProcessor before方法
 * 5.InitialingBean接口的方法执行啦!
 * 6.初始化
 * 7.初始化前 BeanPostProcessor after方法
 * 8.使用Bean
 * 9.DisposableBean接口的方法执行啦!
 * 10.销毁Bean
 *
 */
